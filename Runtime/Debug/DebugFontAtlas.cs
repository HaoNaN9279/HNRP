    /// 调试字模图集：布局常量 + 内置位图字模的程序化生成。
    /// </summary>
    /// <remarks>
    /// <para><b>图集规格</b>（与 <c>DebugText.hlsl</c> 的 <c>DEBUG_FONT_*</c> 宏一致）：
    /// 256×128、单通道遮罩（存放在 alpha）、16×16 像素一个字块、16 列 × 8 行，
    /// 覆盖 ASCII <see cref="DebugStringCodec.AsciiStart"/>..<see cref="DebugStringCodec.AsciiEnd"/>。</para>
    /// <para><b>为何用内置位图字模而非系统字体烘焙</b>：Unity 的动态字体图集会把部分
    /// 字形旋转 90° 存储，而 <c>CharacterInfo</c> 未提供旋转标记，导致 CPU 侧按
    /// UV 直接拷贝字形必然错位；同时 Player 不保证存在可用的系统字体。
    /// 内置 5×7 位图字模由本文件程序化生成，零资产、零字体依赖、Editor 与 Player
    /// 行为完全一致。</para>
    /// <para><b>字形尺寸</b>：5×7 位图，在 16×16 字块内按 2×2 像素块放大，
    /// 占据块内 x ∈ [3, 12]、y ∈ [1, 14]（y 自上而下）。</para>
    /// </remarks>
    public static class DebugFontAtlas
    {
        /// <summary>图集宽度（像素）。</summary>
        public const int Width = 256;

        /// <summary>图集高度（像素）。</summary>
        public const int Height = 128;

        /// <summary>单一字块的边长（像素）。</summary>
        public const int CellSize = 16;

        /// <summary>字块列数。</summary>
        public const int CellsX = Width / CellSize;

        /// <summary>字块行数。</summary>
        public const int CellsY = Height / CellSize;

        /// <summary>字符步进宽度（像素）；字形宽 10 + 间距 2。</summary>
        public const int StepWidth = 12;

        /// <summary>位图字形的列数。</summary>
        public const int GlyphWidth = 5;

        /// <summary>位图字形的行数。</summary>
        public const int GlyphHeight = 7;

        /// <summary>字块内字形的横向起点（像素）。</summary>
        private const int GlyphOffsetX = 3;

        /// <summary>字块内字形的纵向起点（自上而下，像素）。</summary>
        private const int GlyphOffsetY = 1;

        /// <summary>字形像素在字块内的放大倍数。</summary>
        private const int GlyphScale = 2;

        /// <summary>
        /// 生成内置位图字模图集（白色 RGB + alpha 遮罩）。
        /// </summary>
        /// <returns>256×128 的字模纹理；调用方负责释放。</returns>
        public static Texture2D CreateDefault()
        {
            var texture = new Texture2D(Width, Height, TextureFormat.RGBA32, false, true)
            {
                name = "HNRPDebugFont",
                filterMode = FilterMode.Point,
                wrapMode = TextureWrapMode.Clamp,
                hideFlags = HideFlags.HideAndDontSave,
            };

            var pixels = new Color32[Width * Height];
            for (int i = 0; i < pixels.Length; i++)
            {
                pixels[i] = new Color32(255, 255, 255, 0);
            }

            for (int index = 0; index < Glyphs.Length; index++)
            {
                int ascii = DebugStringCodec.AsciiStart + index;
                if (ascii > DebugStringCodec.AsciiEnd)
                {
                    break;
                }

                StampGlyph(pixels, index, Glyphs[index]);
            }

            texture.SetPixels32(pixels);
            texture.Apply(false, false);
            return texture;
        }

        /// <summary>
        /// 把一个字形写入图集。
        /// </summary>
        /// <param name="pixels">图集像素（索引 0 为左下角，y 向上）。</param>
        /// <param name="glyphIndex">字形下标（ASCII - <see cref="DebugStringCodec.AsciiStart"/>）。</param>
        /// <param name="pattern">7 行 × 5 列的图案，空格与分隔符被忽略。</param>
        private static void StampGlyph(Color32[] pixels, int glyphIndex, string pattern)
        {
            int cellX = (glyphIndex % CellsX) * CellSize;
            int cellY = (glyphIndex / CellsX) * CellSize;

            int read = 0;
            for (int row = 0; row < GlyphHeight; row++)
            {
                for (int col = 0; col < GlyphWidth; col++)
                {
                    // 跳过空格 / 斜杠等分隔符。
                    while (read < pattern.Length && pattern[read] != '.' && pattern[read] != '#')
                    {
                        read++;
                    }

                    bool on = read < pattern.Length && pattern[read] == '#';
                    read++;

                    if (!on)
                    {
                        continue;
                    }

                    for (int sy = 0; sy < GlyphScale; sy++)
                    {
                        int topDownRow = GlyphOffsetY + (row * GlyphScale) + sy;
                        int atlasY = cellY + (CellSize - 1 - topDownRow);
                        if (atlasY < 0 || atlasY >= Height)
                        {
                            continue;
                        }

                        for (int sx = 0; sx < GlyphScale; sx++)
                        {
                            int atlasX = cellX + GlyphOffsetX + (col * GlyphScale) + sx;
                            if (atlasX < cellX || atlasX >= cellX + CellSize || atlasX >= Width)
                            {
                                continue;
                            }

                            pixels[(atlasY * Width) + atlasX] = new Color32(255, 255, 255, 255);
                        }
                    }
                }
            }
        }

